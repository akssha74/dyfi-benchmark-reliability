#!/usr/bin/env python3
"""Build JEAS-only engineering-use assets from frozen manuscript inputs.

This script performs no model fitting and changes no scientific result. It reads
the frozen ``manuscript/derived/asset_inputs.json`` and renders:

* an engineering failure-mode table;
* a candidate-model qualification table; and
* a vector workflow figure describing the benchmark decision contract.
"""
from __future__ import annotations

import datetime as dt
import json
import os
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch

HERE = Path(__file__).resolve().parent
MAN = HERE.parent
INPUT = Path(os.environ.get(
    "DYFI_ASSET_INPUTS",
    str(MAN / "derived" / "asset_inputs.json")
))
if not INPUT.exists():
    INPUT = HERE / "frozen_inputs" / "asset_inputs.json"
TABLES = HERE / "tables"
FIGURES = HERE / "figures"


def f3(value: float) -> str:
    return f"{value:.3f}"


def f4(value: float) -> str:
    return f"{value:.4f}"


def write_failure_modes() -> None:
    rows = [
        ("Catalogue revision", "Non-identical event population", "Frozen access instant + SHA-256 release"),
        ("Outcome-derived field", "Label leakage", "F1/F2 schema audit"),
        ("Identifier or downstream proxy", "Proxy leakage", "F3/F4 field audit"),
        ("Sequence crosses roles", "Dependent-event contamination", "F5 sequence-role audit"),
        ("Temporal-cutoff violation", "Future information in development", "F6 temporal audit"),
        ("Point-score ranking", "False model-superiority claim", "Paired sequence-cluster interval"),
        ("Environment drift", "Irreproducible scores/artifacts", "Pinned environment + reconstruction hash"),
    ]
    lines = [
        "% GENERATED by build_utility_assets.py -- do not edit.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\caption{Engineering failure modes addressed by the benchmark qualification contract}",
        r"\label{tab:engineering-failures}",
        r"\begin{tabular}{p{0.20\textwidth}p{0.28\textwidth}p{0.34\textwidth}}",
        r"\toprule",
        r"Failure source & Invalid engineering conclusion & Qualification control \\",
        r"\midrule",
    ]
    lines.extend(" & ".join(row) + r" \\" for row in rows)
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table*}",
        "",
    ]
    (TABLES / "engineering_failure_modes.tex").write_text("\n".join(lines))


def write_qualification(asset: dict) -> None:
    labels = {
        "B0_no_skill": "B0 no-skill",
        "B1_magnitude_only_logit": "B1 magnitude-only logistic",
        "B2_source_only_logit": "B2 source-only logistic",
        "B4_random_forest": "B4 random forest",
        "B5_xgboost": "B5 XGBoost",
    }
    lines = [
        "% GENERATED by build_utility_assets.py -- do not edit.",
        r"\begin{table*}[t]",
        r"\centering",
        r"\small",
        r"\caption{Worked candidate-model qualification using the frozen temporal holdout}",
        r"\label{tab:qualification}",
        r"\begin{tabular}{p{0.25\textwidth}p{0.12\textwidth}p{0.17\textwidth}p{0.23\textwidth}p{0.16\textwidth}}",
        r"\toprule",
        r"Candidate & Audit gate & Holdout Brier [95\% CI] & Brier difference vs B0 [95\% CI] & Contract decision \\",
        r"\midrule",
    ]
    baseline = asset["per_baseline"]
    ranking = asset["ranking_vs_reference"]
    b0 = baseline["B0_no_skill"]
    lines.append(
        f"{labels['B0_no_skill']} & Pass (reference) & "
        f"{f3(b0['brier'])} [{f3(b0['brier_ci'][0])}, {f3(b0['brier_ci'][1])}]"
        r" & --- & Reference only \\"
    )
    for key in ("B1_magnitude_only_logit", "B2_source_only_logit", "B4_random_forest", "B5_xgboost"):
        perf = baseline[key]
        comp = ranking[f"{key}_vs_B0_no_skill"]
        lines.append(
            f"{labels[key]} & Pass & "
            f"{f3(perf['brier'])} [{f3(perf['brier_ci'][0])}, {f3(perf['brier_ci'][1])}] & "
            f"{f4(comp['point_diff_a_minus_b'])} "
            f"[{f4(comp['ci'][0])}, {f4(comp['ci'][1])}] & "
            r"Supported vs B0 \\"
        )
    lines.append(
        r"B3 expanded-metadata logistic & Fail & --- & --- & "
        r"Inadmissible: event year reveals temporal axis \\"
    )
    pair = asset["pairwise_ranking_stability"]["pairwise_matrix"][
        "B2_source_only_logit_vs_B5_xgboost"
    ]
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\par\vspace{2pt}\footnotesize\emph{Decision rule.} A candidate is first "
        r"admitted by the schema, proxy, role, and temporal audits. A lower paired "
        r"Brier interval that excludes zero supports improvement over the declared "
        r"reference; otherwise the comparison remains unresolved. All four learned "
        r"baselines improve over B0. B2 versus B5 remains unresolved "
        f"(B2$-$B5 {f4(pair['point_diff_a_minus_b'])}, "
        f"95\\% CI [{f4(pair['ci'][0])}, {f4(pair['ci'][1])}]), "
        r"so the contract prevents a false winner declaration.",
        r"\end{table*}",
        "",
    ]
    (TABLES / "candidate_qualification.tex").write_text("\n".join(lines))


def write_workflow() -> None:
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10})
    fig, ax = plt.subplots(figsize=(10.2, 4.1))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 4)
    ax.axis("off")

    boxes = [
        (0.25, 2.45, 1.45, 0.75, "Candidate\nmodel"),
        (2.05, 2.45, 1.45, 0.75, "Schema +\nleakage audit"),
        (3.85, 2.45, 1.45, 0.75, "Frozen roles +\ntemporal holdout"),
        (5.65, 2.45, 1.45, 0.75, "Proper score +\npaired interval"),
        (7.45, 2.45, 2.05, 0.75, "Supported improvement\nor unresolved result"),
    ]
    for x, y, w, h, text in boxes:
        patch = FancyBboxPatch(
            (x, y),
            w,
            h,
            boxstyle="round,pad=0.04,rounding_size=0.08",
            facecolor="#edf4f8",
            edgecolor="#315b73",
            linewidth=1.2,
        )
        ax.add_patch(patch)
        ax.text(x + w / 2, y + h / 2, text, ha="center", va="center")
    for left, right in zip(boxes[:-1], boxes[1:]):
        x1 = left[0] + left[2]
        x2 = right[0]
        y = left[1] + left[3] / 2
        ax.add_patch(FancyArrowPatch((x1, y), (x2, y), arrowstyle="->", mutation_scale=13))

    reject = FancyBboxPatch(
        (1.55, 0.55),
        2.9,
        0.75,
        boxstyle="round,pad=0.04,rounding_size=0.08",
        facecolor="#f8eeee",
        edgecolor="#884c4c",
        linewidth=1.2,
    )
    ax.add_patch(reject)
    ax.text(3.0, 0.925, "Fail closed: inadmissible comparison", ha="center", va="center")
    ax.add_patch(FancyArrowPatch((2.775, 2.45), (3.0, 1.3), arrowstyle="->", mutation_scale=13))

    ax.text(
        7.25,
        1.0,
        "Interval excludes zero: supported relative to reference\n"
        "Interval includes zero: unresolved; do not name a winner",
        ha="center",
        va="center",
        fontsize=9.0,
    )
    FIGURES.mkdir(parents=True, exist_ok=True)
    metadata = {
        "Creator": "build_utility_assets.py",
        "Producer": "Matplotlib",
        "CreationDate": dt.datetime(2010, 1, 1, tzinfo=dt.timezone.utc),
        "ModDate": dt.datetime(2010, 1, 1, tzinfo=dt.timezone.utc),
    }
    fig.savefig(FIGURES / "fig_candidate_workflow.pdf", bbox_inches="tight", metadata=metadata)
    fig.savefig(FIGURES / "fig_candidate_workflow.png", bbox_inches="tight", dpi=300)
    plt.close(fig)


def main() -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    asset = json.loads(INPUT.read_text())
    write_failure_modes()
    write_qualification(asset)
    write_workflow()


if __name__ == "__main__":
    main()
