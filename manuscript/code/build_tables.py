"""Deterministic generator for the manuscript's result tables.

Reads only manuscript/derived/asset_inputs.json (itself built and verified from
frozen released artifacts) and emits, for each table, a standalone LaTeX float
fragment (\\input-able) plus a full-precision CSV. Captions and claim-neutral
interpretations are registered in manuscript/derived/table_captions.json.

Pure standard library; no plotted or hand-edited values. Numbers are FORMATTED
for the LaTeX fragment (fixed decimals) but the CSV carries the released
precision so nothing is silently lost.
"""
from __future__ import annotations

import csv
import io
import os
from typing import Dict, List, Optional

import asset_common as ac

DERIVED = os.path.join(ac.ROOT, "manuscript", "derived")
TABLES = os.path.join(ac.ROOT, "manuscript", "tables")


def f3(x: Optional[float]) -> str:
    return "--" if x is None else f"{float(x):.3f}"


def f4(x: Optional[float]) -> str:
    return "--" if x is None else f"{float(x):.4f}"


def f2(x: Optional[float]) -> str:
    return "--" if x is None else f"{float(x):.2f}"


def intc(x) -> str:
    return "--" if x is None else str(int(x))


def esc(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("_", r"\_")
            .replace("%", r"\%").replace("&", r"\&").replace("#", r"\#"))


def short_hash(h: Optional[str]) -> str:
    return "--" if not h else f"{h[:12]}\\ldots"


def _table_float(label: str, caption: str, colspec: str,
                 header: List[str], body_rows: List[List[str]],
                 note: str) -> str:
    lines = [
        r"% GENERATED by manuscript/code/build_tables.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{colspec}}}",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
    ]
    for row in body_rows:
        lines.append(" & ".join(row) + r" \\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        rf"\par\vspace{{2pt}}\footnotesize\emph{{Note.}} {note}",
        r"\end{table}",
        "",
    ]
    return "\n".join(lines)


def _write_csv(name: str, header: List[str], rows: List[List[str]]) -> str:
    path = os.path.join(TABLES, name)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    for r in rows:
        w.writerow(["" if c is None else c for c in r])
    return ac.write_text(path, buf.getvalue())


def build() -> Dict[str, object]:
    D = ac.common.load_json(os.path.join(DERIVED, "asset_inputs.json"))
    shas: Dict[str, str] = {}
    captions: Dict[str, Dict[str, str]] = {}

    # ---- Table 1: cohort / role ----------------------------------------
    cf = D["cohort_flow"]
    roles = cf["roles"]
    t1_rows_csv = [["stage", "n_events", "n_positive", "prevalence", "n_sequences"]]
    body = []
    body.append([r"USGS DYFI records with $M\geq5$ (frozen snapshot)", intc(cf["fdsn_features_pinned_snapshot"]), "--", "--", "--"])
    body.append([r"Eligible (at least 10 felt reports)", intc(cf["n_eligible_events"]), intc(cf["n_eligible_severe"]), f3(cf["eligible_prevalence"]), intc(cf["sequences"]["all_eligible"])])
    body.append([r"\quad Train", intc(roles["train"]["n"]), intc(roles["train"]["positive"]), f3(roles["train"]["prevalence"]), "--"])
    body.append([r"\quad Development", intc(roles["development"]["n"]), intc(roles["development"]["positive"]), f3(roles["development"]["prevalence"]), "--"])
    body.append([r"\quad Construction (train+dev)", intc(cf["construction_total"]["n"]), intc(cf["construction_total"]["positive"]), f3(cf["construction_total"]["prevalence"]), intc(cf["sequences"]["construction"])])
    body.append([r"\quad External temporal holdout", intc(roles["external_temporal_holdout"]["n"]), intc(roles["external_temporal_holdout"]["positive"]), f3(roles["external_temporal_holdout"]["prevalence"]), intc(cf["sequences"]["holdout"])])
    body.append([r"Temporal-straddle excluded", intc(cf["temporal_straddle_excluded"]), intc(cf["temporal_straddle"]["positive"]), "--", "--"])
    reconciliation = (
        " The eligible severe count reconciles as " + intc(cf["n_eligible_severe"]) + " = "
        + intc(roles["train"]["positive"]) + " (train) $+$ "
        + intc(roles["development"]["positive"]) + " (development) $+$ "
        + intc(roles["external_temporal_holdout"]["positive"]) + " (holdout) $+$ "
        + intc(cf["temporal_straddle"]["positive"]) + " (straddle exclusion). Thus the "
        + intc(cf["n_role_assigned"]) + " role-assigned events contain "
        + intc(cf["n_role_assigned_severe"]) + " severe events.")
    for r in body:
        t1_rows_csv.append([r[0].replace("\\quad ", "").replace(r"\_", "_").replace(r"$\geq$", ">="), r[1], r[2], r[3], r[4]])
    shas["cohort_roles.tex"] = ac.write_text(
        os.path.join(TABLES, "cohort_roles.tex"),
        _table_float(
            "tab:cohort", "Cohort accounting and outcome-independent role assignment for the frozen USGS DYFI $M\\geq5$ snapshot.",
            "lrrrr",
            ["Stage", "Events", "Severe", "Severe rate", "Sequences"], body,
            "Roles were fixed without using outcomes. Two source-verification records were removed before the 2,362-event eligible cohort was constructed and are not included in these rows. Severe $=1$ when an event's maximum community decimal intensity (CDI) is at least 6." + reconciliation))
    shas["cohort_roles.csv"] = _write_csv("cohort_roles.csv", t1_rows_csv[0], t1_rows_csv[1:])
    captions["cohort_roles"] = {
        "caption": "Cohort construction and role assignment.",
        "claim_neutral_interpretation": "Descriptive cohort accounting; the partition is exhaustive and disjoint (1573+357+430+2 = 2362) and roles are outcome-independent. No performance claim.",
    }

    # ---- Table 2: endpoint / threshold sensitivity ---------------------
    ep = D["endpoint"]
    ts = ep["threshold_sensitivity"]
    body = []
    csv2 = [["threshold", "holdout_prevalence", "brier", "auroc"]]
    for thr in ("5.5", "6.0", "6.5"):
        e = ts[thr]
        star = r" $^a$" if thr == "6.0" else ""
        body.append([f"{thr}{star}", f3(e["prevalence"]), f3(e["brier"]), f3(e["auroc"])])
        csv2.append([thr, e["prevalence"], e["brier"], e["auroc"]])
    shas["endpoint_threshold_sensitivity.tex"] = ac.write_text(
        os.path.join(TABLES, "endpoint_threshold_sensitivity.tex"),
        _table_float(
            "tab:threshold",
            "Sensitivity to the severe-intensity cutoff on the temporal holdout, evaluated with the source-only logistic regression (B2).",
            "lrrr",
            ["Maximum CDI cutoff", "Severe rate", "Brier score", "AUROC"], body,
            "$^a$~Prespecified primary cutoff ($\\geq 6$). CDI denotes community decimal intensity. In the construction sample, " + f3(ep["near_threshold_fraction_construction"]) + " of events lie within 0.5 CDI units of the primary cutoff, and the no-skill Brier score is " + f3(ep["no_skill_brier_floor_construction"]) + ". Lower Brier score and higher AUROC indicate better performance."))
    shas["endpoint_threshold_sensitivity.csv"] = _write_csv("endpoint_threshold_sensitivity.csv", csv2[0], csv2[1:])
    captions["endpoint_threshold_sensitivity"] = {
        "caption": "Endpoint threshold sensitivity.",
        "claim_neutral_interpretation": "Shows the endpoint is not a single-grid artifact; prevalence and probe scores move smoothly across 5.5/6.0/6.5. No model-superiority claim.",
    }

    # ---- Table 3: baseline performance + uncertainty + calibration -----
    pb = D["per_baseline"]
    order = ["B0_no_skill", "B1_magnitude_only_logit", "B2_source_only_logit", "B4_random_forest", "B5_xgboost"]
    body = []
    csv3 = [["baseline", "brier", "brier_ci_lower", "brier_ci_upper", "log_loss", "auroc",
             "calibration_status", "calibration_intercept", "calibration_slope",
             "accuracy", "tp", "fp", "tn", "fn"]]
    for bid in order:
        e = pb[bid]
        ci = e["brier_ci"]
        cal = e["calibration_status"]
        cal_disp = "INFEASIBLE" if cal != "OK" else (f2(e["calibration_intercept"]) + " / " + f2(e["calibration_slope"]))
        conf = e["confusion_at_threshold"]
        body.append([
            esc(bid), f3(e["brier"]), f"[{f3(ci[0])}, {f3(ci[1])}]", f3(e["log_loss"]),
            (f3(e["auroc"]) if isinstance(e["auroc"], (int, float)) else esc(str(e["auroc"]))),
            cal_disp, f2(conf["accuracy"]),
        ])
        csv3.append([bid, e["brier"], ci[0], ci[1], e["log_loss"], e["auroc"], cal,
                     e["calibration_intercept"], e["calibration_slope"], conf["accuracy"],
                     conf["tp"], conf["fp"], conf["tn"], conf["fn"]])
    shas["baseline_performance.tex"] = ac.write_text(
        os.path.join(TABLES, "baseline_performance.tex"),
        _table_float(
            "tab:baselines",
            "Per-baseline performance on the temporal holdout ($n=430$) with sequence-cluster bootstrap 95\\% CIs and derived calibration states.",
            "lccccc c",
            ["Baseline", "Brier", "95\\% CI", "Log-loss", "AUROC", "Calibration$^a$", "Accuracy"],
            body,
            "$^a$~Intercept / slope. These values cannot be estimated for B0 because it assigns the same probability to every event. B3 includes event year and is therefore omitted from the temporal holdout (Table~\\ref{tab:exclusions}). Accuracy uses the probability cutoff of 0.5 fixed on the development set. Lower Brier score and log-loss are better; higher AUROC and accuracy are better. The two lowest-Brier models cannot be distinguished in their direct paired comparison."))
    shas["baseline_performance.csv"] = _write_csv("baseline_performance.csv", csv3[0], csv3[1:])
    captions["baseline_performance"] = {
        "caption": "Per-baseline performance with uncertainty and calibration states.",
        "claim_neutral_interpretation": "Reports proper scores, bootstrap CIs, and calibration feasibility for the fixed baseline suite. B0's INFEASIBLE calibration is a derived state. No winning-model claim.",
    }

    # ---- Table 4: leakage-gap ------------------------------------------
    lk = D["leakage_inflation_headline"]
    ps = lk["per_scheme"]
    body = []
    csv4 = [["split_scheme", "brier", "auroc", "log_loss", "n_folds_populated"]]
    labels = {"random_event": "Random-event (naive)", "event_grouped": "Event-grouped (control)", "sequence_grouped": "Sequence-grouped (primary)"}
    for k in ("random_event", "event_grouped", "sequence_grouped"):
        e = ps[k]
        body.append([labels[k], f4(e["brier"]), f4(e["auroc"]), f4(e["log_loss"]), intc(e["n_folds_populated"])])
        csv4.append([k, e["brier"], e["auroc"], e["log_loss"], e["n_folds_populated"]])
    shas["leakage_gap.tex"] = ac.write_text(
        os.path.join(TABLES, "leakage_gap.tex"),
        _table_float(
            "tab:leakage",
            "Cross-validated performance of the fixed random-forest diagnostic (B4) under three fold-assignment schemes in the construction sample.",
            "lrrrr",
            ["Fold assignment", "Brier score", "AUROC", "Log-loss", "Folds"], body,
            "Using unrounded values, the sequence-grouped minus random-event Brier difference is " + f4(lk["brier_inflation_seq_minus_random"]) + "; the random-event minus sequence-grouped AUROC difference is " + f4(lk["auroc_inflation_random_minus_seq"]) + ". The preregistration required uncertainty but did not define the paired interval estimator; the executed report retained point estimates only. This deviation is disclosed, and no post-hoc interval or equivalence claim is added. Because there is one row per event, event grouping imposes the same grouping constraint as random-event assignment, but its deterministic fold allocation is different and can produce different scores."))
    shas["leakage_gap.csv"] = _write_csv("leakage_gap.csv", csv4[0], csv4[1:])
    captions["leakage_gap"] = {
        "caption": "Leakage-inflation across split schemes.",
        "claim_neutral_interpretation": "Quantifies naive-vs-grouped split optimism for a fixed diagnostic model. The gap is near zero and slightly reversed, so it is reported as a null result rather than a gain.",
    }

    # ---- Table 5: full pairwise matrix (F2) ----------------------------
    pw = D["pairwise_ranking_stability"]["pairwise_matrix"]
    body = []
    csv5 = [["baseline_a", "baseline_b", "point_diff_a_minus_b", "ci_lower", "ci_upper",
             "prob_a_better", "prob_b_better", "prob_tie", "status", "directional_better"]]
    for key in sorted(pw):
        e = pw[key]
        body.append([
            esc(e["baseline_a"]), esc(e["baseline_b"]), f4(e["point_diff_a_minus_b"]),
            f"[{f4(e['ci'][0])}, {f4(e['ci'][1])}]", f3(e["prob_a_better"]), f3(e["prob_tie"]),
            ("resolved" if e["resolved"] else "unresolved"),
            (esc(e["directional_better_baseline"]) if e["directional_better_baseline"] else "--"),
        ])
        csv5.append([e["baseline_a"], e["baseline_b"], e["point_diff_a_minus_b"], e["ci"][0], e["ci"][1],
                     e["prob_a_better"], e["prob_b_better"], e["prob_tie"], e["status"],
                     e["directional_better_baseline"]])
    shas["pairwise_matrix.tex"] = ac.write_text(
        os.path.join(TABLES, "pairwise_matrix.tex"),
        _table_float(
            "tab:pairwise",
            "Pairwise comparison of baseline Brier scores on the temporal holdout using a paired sequence-cluster bootstrap.",
            "llccc l",
            ["Model A", "Model B", "A $-$ B", "95\\% CI", "$P$(A better)", "Conclusion"],
            [[r[0], r[1], r[2], r[3], r[4], r[6]] for r in body],
            "Lower Brier score is better, so a negative A $-$ B difference favors model A. ``Resolved'' means that the 95\\% interval excludes zero; ``unresolved'' means that it includes zero. Because no numerical equivalence margin was specified before analysis, unresolved comparisons are not labelled equivalent. B0 is the no-skill reference; B1 is magnitude-only logistic regression; B2 is source-only logistic regression; B4 is random forest; and B5 is XGBoost."))
    shas["pairwise_matrix.csv"] = _write_csv("pairwise_matrix.csv", csv5[0], csv5[1:])
    captions["pairwise_matrix"] = {
        "caption": "Full pairwise ranking-stability matrix.",
        "claim_neutral_interpretation": "Complete directional stability for every eligible pair. Equivalent class not asserted (no registered margin). Reinforces no-winning-model; overturns no headline.",
    }

    # ---- Table 6: temporal / geographic subgroup summaries -------------
    ts_slice = D["slices"]["temporal"]
    gsum = D["slices"]["geographic_summary"]
    body = []
    csv6 = [["slice_type", "slice", "n", "brier", "auroc"]]
    for yr in sorted(ts_slice):
        e = ts_slice[yr]
        body.append([f"Temporal {yr}", intc(e["n"]), f3(e["brier"]),
                     (f3(e["auroc"]) if isinstance(e.get("auroc"), (int, float)) else "--")])
        csv6.append(["temporal", yr, e["n"], e["brier"], e.get("auroc")])
    body.append([f"Geographic cells within temporal holdout ({intc(gsum['n_cells'])})", intc(gsum["sum_n"]),
                 f"{f3(gsum['brier_median'])} (med.)", "--"])
    csv6.append(["geographic_subgroup_summary", f"{gsum['n_cells']}_cells", gsum["sum_n"], gsum["brier_median"], None])
    shas["slices.tex"] = ac.write_text(
        os.path.join(TABLES, "slices.tex"),
        _table_float(
            "tab:slices",
            "Temporal and geographic subgroup summaries within the temporal holdout for the source-only logistic regression (B2).",
            "lrrr",
            ["Subset", "Events", "Brier score", "AUROC"], body,
            "The geographic row partitions the same 430 temporal-holdout predictions into " + intc(gsum["n_cells"]) + " occupied 10$^\\circ$ cells. It is a descriptive subgroup summary, not a leave-region-out or external geographic evaluation. The entry is the median cell-level Brier score; cell values range from " + f3(gsum["brier_min"]) + " to " + f3(gsum["brier_max"]) + " and are included in the public release."))
    # full geographic to companion CSV
    gfull = D["slices"]["geographic_full"]
    gcsv = [["region_cell", "n", "brier", "brier_status"]]
    for cell in sorted(gfull):
        e = gfull[cell]
        gcsv.append([cell, e["n"], e.get("brier"), e.get("brier_status")])
    shas["slices_geographic_full.csv"] = _write_csv("slices_geographic_full.csv", gcsv[0], gcsv[1:])
    shas["slices.csv"] = _write_csv("slices.csv", csv6[0], csv6[1:])
    captions["slices"] = {
        "caption": "Temporal and geographic subgroup summaries.",
        "claim_neutral_interpretation": "Descriptive subgroups of the temporal holdout. The geographic cells are not a leave-region-out or external geographic evaluation.",
    }

    # ---- Table 7: exclusions / deviations ------------------------------
    body = [
        ["B3 expanded-metadata model", "Omitted from temporal holdout", "It includes event year, which would reveal the evaluation period."],
        ["Published DYFI intensity equation", "Omitted as a comparator", "It requires unavailable site distance and tectonic-region inputs, plus an unvalidated conversion to event probabilities."],
        ["Registered geographic transport evaluation", "Not executed", "The released geographic result is a subgroup summary of temporal-holdout predictions, not a leave-region-out evaluation; no geographic generalization claim is made."],
        ["Split-contrast uncertainty", "Deviation disclosed", "The preregistration required uncertainty but did not define the paired interval estimator; the executed result retained point estimates only, and no post-hoc interval is added."],
        ["Equivalence interpretation", "Descriptive comparisons only", "No numerical equivalence margin was specified before analysis, so the paper reports resolved or unresolved differences without claiming equivalence."],
    ]
    csv7 = [["item", "disposition", "reason"]]
    for r in body:
        csv7.append([r[0].replace("\\_", "_").replace("--", "-").replace("`", "'"), r[1], r[2].replace("\\_", "_").replace("`", "'")])
    shas["exclusions_deviations.tex"] = ac.write_text(
        os.path.join(TABLES, "exclusions_deviations.tex"),
        _table_float(
            "tab:exclusions",
            "Excluded analyses and disclosed deviations affecting interpretation.",
            ">{\\raggedright\\arraybackslash}p{0.27\\linewidth} >{\\raggedright\\arraybackslash}p{0.22\\linewidth} >{\\raggedright\\arraybackslash}p{0.41\\linewidth}",
            ["Decision", "Treatment", "Rationale"], body,
            "These decisions were recorded before, or disclosed with, the analysis. No result, subset, cutoff, or comparison was omitted because of its observed outcome."))
    shas["exclusions_deviations.csv"] = _write_csv("exclusions_deviations.csv", csv7[0], csv7[1:])
    captions["exclusions_deviations"] = {
        "caption": "Protocol decisions affecting interpretation.",
        "claim_neutral_interpretation": "Explains excluded comparators and records, the lack of an equivalence claim, integrity bookkeeping, and interpretation of the near-zero split comparison.",
    }

    # ---- Table 8: data / reproducibility manifest ----------------------
    rm = D["reproducibility_manifest"]
    body = [
        ["Frozen source data", f"{int(rm['fdsn_features']):,} USGS DYFI records", "A complete SHA-256 digital fingerprint is archived."],
        ["Protected holdout use", "Opened once", "A single-use safeguard prevented repeat evaluation."],
        ["Independent reconstruction", "Two clean reruns", "Both reproduced the recorded results and holdout predictions exactly."],
        ["Model fitting", f"{intc(rm['fit_count'])} fits (prespecified cap: {intc(rm['fit_cap'])})", "The recorded run remained within its computational budget."],
        ["Software environment", "Python " + esc(rm["python"]) + "; package versions archived", "Exact versions are fixed for reproduction."],
        ["Integrity audit", intc(rm["n_load_bearing_files_matched"]) + " of " + intc(rm["n_load_bearing_files_matched"]) + " analysis files matched", "Three self-referential bookkeeping records are reported separately."],
        ["Licensing", esc(rm["licences"]["data"]) + " data; " + esc(rm["licences"]["code"]) + " code; USGS public-domain source", "Terms permit independent reuse and verification."],
    ]
    csv8 = [["field", "value"]]
    csv8.append(["source_snapshot_sha256", rm["source_snapshot_sha256"]])
    csv8.append(["result_hash", rm["result_hash"]])
    csv8.append(["predictions_digest", rm["predictions_digest"]])
    csv8.append(["fit_ledger_digest", rm["fit_ledger_digest"]])
    csv8.append(["reconstruction_pipeline_digest", rm["reconstruction_pipeline_digest"]])
    csv8.append(["fit_count", rm["fit_count"]])
    csv8.append(["run_token_consumed_count", rm["run_token_consumed_count"]])
    csv8.append(["python", rm["python"]])
    for k, v in rm["environment"].items():
        csv8.append([f"pin_{k}", v])
    shas["reproducibility_manifest.tex"] = ac.write_text(
        os.path.join(TABLES, "reproducibility_manifest.tex"),
        _table_float(
            "tab:repro",
            "Reproducibility safeguards and verification results.",
            ">{\\raggedright\\arraybackslash}p{0.25\\linewidth} >{\\raggedright\\arraybackslash}p{0.31\\linewidth} >{\\raggedright\\arraybackslash}p{0.34\\linewidth}",
            ["Check", "Recorded result", "What it establishes"], body,
            "Complete digital fingerprints, environment details, and machine-readable verification records are included in the tagged public release."))
    shas["reproducibility_manifest.csv"] = _write_csv("reproducibility_manifest.csv", csv8[0], csv8[1:])
    captions["reproducibility_manifest"] = {
        "caption": "Data and reproducibility manifest.",
        "claim_neutral_interpretation": "Provenance and integrity anchors (hashes, single token, environment pins, licences). Establishes reproducibility, makes no performance claim.",
    }

    cap_sha = ac.write_json_sorted(os.path.join(DERIVED, "table_captions.json"), captions)
    shas["table_captions.json"] = cap_sha
    return shas


if __name__ == "__main__":
    import json
    print(json.dumps(build(), indent=2))
