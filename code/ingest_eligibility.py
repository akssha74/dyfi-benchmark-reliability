"""Deterministic ingestion + eligibility for the USGS DYFI benchmark.

Parses a pinned ComCat/FDSN GeoJSON snapshot (producttype=dyfi) into canonical
event rows, applies the ascertainment eligibility rule (num_responses >= 10 AND a
computable maxCDI), performs strict typed parsing (fractional-into-integer is
rejected, not truncated), derives origin_year and region_code, and drops
quarantined events.

Honesty on the eligibility rule: num_responses (the count of felt reports) is a
POST-REPORT ASCERTAINMENT quantity. It is only known after the public submits
reports, it is generated by the same felt-shaking process that produces the
label, and it is correlated with the outcome. It is therefore NOT
outcome-independent and must not be described as such. Requiring
num_responses >= 10 is a data-informed ascertainment/quality gate (a minimum
sample for a stable event-maximum CDI), disclosed as such. Consequently:

  * this resource is a RETROSPECTIVE benchmark only; it supports no pre-report /
    real-time / operational prediction claim, because at prediction time the
    response count does not yet exist;
  * the eligibility filter is a data-informed selection, not an outcome-blind
    one, and any downstream prevalence read from the eligible table is likewise
    data-informed (see the outcome-boundary disclosure).

num_responses is never a model predictor (see common.NON_PREDICTIVE_COLUMNS).
"""
from __future__ import annotations

import datetime
import json
import sys
from typing import Dict, List, Optional, Sequence

from common import (
    region_code,
    strict_float,
    strict_int,
    write_csv,
)

CANONICAL_COLUMNS = (
    "event_id",
    "magnitude",
    "magnitude_type",
    "depth_km",
    "latitude",
    "longitude",
    "origin_time",
    "origin_year",
    "region_code",
    "num_responses",
    "max_cdi",
)

# Post-report ascertainment gate: minimum felt-report count for a stable event
# maximum CDI. This is a data-informed quality threshold, NOT outcome-blind.
MIN_RESPONSES = 10


def _origin_year(epoch_ms: int) -> int:
    dt = datetime.datetime.fromtimestamp(epoch_ms / 1000.0, tz=datetime.timezone.utc)
    return dt.year


def _origin_iso(epoch_ms: int) -> str:
    dt = datetime.datetime.fromtimestamp(epoch_ms / 1000.0, tz=datetime.timezone.utc)
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_geojson(
    geojson: Dict,
    quarantine: Optional[Sequence[str]] = None,
) -> Dict[str, object]:
    """Parse a GeoJSON FeatureCollection into eligible canonical event rows.

    Returns {'rows': [...], 'stats': {...}}. This function reads the label field
    (max_cdi) to build the eligible table and applies a POST-REPORT ascertainment
    gate (num_responses >= 10); it does NOT perform any per-event outcome
    INSPECTION beyond that gate, no model fit, and no comparison. Because both the
    eligibility gate and the label depend on the same post-report response
    process, this step is data-informed (aggregate_feasibility_exposed at most),
    not outcome-blind: callers must disclose that prevalence read from the
    resulting table is data-informed and must not treat this selection as
    outcome-independent (see outcome_boundaries).
    """
    quarantine = set(quarantine or [])
    rows: List[Dict[str, object]] = []
    n_features = 0
    n_quarantined = 0
    n_no_cdi = 0
    n_below_min_reports = 0
    seen_ids = set()
    for feat in geojson.get("features", []):
        n_features += 1
        props = feat.get("properties", {}) or {}
        geom = feat.get("geometry", {}) or {}
        eid = feat.get("id")
        if eid is None:
            continue
        if eid in quarantine:
            n_quarantined += 1
            continue
        if eid in seen_ids:
            continue  # reconcile duplicate event ids: keep first occurrence
        cdi = props.get("cdi", None)
        felt = props.get("felt", None)
        if cdi is None:
            n_no_cdi += 1
            continue
        if felt is None or float(felt) < MIN_RESPONSES:
            n_below_min_reports += 1
            continue
        coords = geom.get("coordinates", [None, None, None])
        try:
            lon = strict_float(coords[0], "longitude")
            lat = strict_float(coords[1], "latitude")
            depth = strict_float(coords[2], "depth_km")
            mag = strict_float(props.get("mag"), "magnitude")
            num_resp = strict_int(felt, "num_responses")
            max_cdi = strict_float(cdi, "max_cdi")
            epoch_ms = strict_int(props.get("time"), "origin_time_ms")
        except (ValueError, TypeError, IndexError):
            continue
        seen_ids.add(eid)
        rows.append(
            {
                "event_id": eid,
                "magnitude": mag,
                "magnitude_type": (props.get("magType") or "unknown"),
                "depth_km": depth,
                "latitude": lat,
                "longitude": lon,
                "origin_time": _origin_iso(epoch_ms),
                "origin_year": _origin_year(epoch_ms),
                "region_code": region_code(lat, lon),
                "num_responses": num_resp,
                "max_cdi": max_cdi,
            }
        )
    rows.sort(key=lambda r: (r["origin_time"], r["event_id"]))
    stats = {
        "n_features": n_features,
        "n_quarantined": n_quarantined,
        "n_no_cdi": n_no_cdi,
        "n_below_min_reports": n_below_min_reports,
        "n_eligible": len(rows),
        "min_responses": MIN_RESPONSES,
        "eligibility_rule": "post_report_ascertainment",
        "outcome_independent": False,
        "selection_boundary": "data_informed",
    }
    return {"rows": rows, "stats": stats}


def _cli(argv: List[str]) -> int:
    import argparse

    from common import load_json, write_json

    p = argparse.ArgumentParser(description="Ingest + eligibility for DYFI snapshot")
    p.add_argument("--geojson", required=True, help="pinned FDSN GeoJSON snapshot")
    p.add_argument("--out-csv", required=True, help="eligible event table output")
    p.add_argument("--out-stats", required=True, help="eligibility stats JSON output")
    p.add_argument("--quarantine", nargs="*", default=[])
    args = p.parse_args(argv)

    gj = load_json(args.geojson)
    res = parse_geojson(gj, quarantine=args.quarantine)
    write_csv(args.out_csv, res["rows"], CANONICAL_COLUMNS)
    write_json(args.out_stats, res["stats"])
    print("eligible:", res["stats"]["n_eligible"])
    return 0


if __name__ == "__main__":
    sys.exit(_cli(sys.argv[1:]))
